        //如果不是floor，重新生成
        while (!world[X][Y].equals(Tileset.FLOOR)) {
            X = uniform(RANDOM, 0, BACK_WIDTH);
            Y = uniform(RANDOM, 0, BACK_HEIGHT);
        }


        //设置形状
        TETile you = new TETile('@', Color.magenta, cyan, "You", 100);
        world[X][Y] = you;


