                            saveTXT.print(',');

                            step++;
                            System.out.println("Yes" + step);
                            //如何区分金币？不是floor就是
                            if (world[X][Y + 1].description().equals("Coin")) {
                                System.out.println("Coin --" + step);
                                numCoins--;
                            }

                            //目标点变成@
                            world[X][Y + 1] = you;
                            //原位置变回地板
                            world[X][Y] = Tileset.FLOOR;
                            //更新X，Y坐标
